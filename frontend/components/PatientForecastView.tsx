'use client';

import React, { useState, useEffect } from 'react';
import Link from 'next/link';
import { PATIENTS, Patient } from '@/lib/data';
import { CopilotReport, getPatient, getPatientCopilotReport, getStoredCustomPatients } from '@/lib/api';
import PatientNavHeader from '@/components/PatientNavHeader';
import StatusChip from '@/components/StatusChip';

export default function PatientForecastView({ patientId, initialPatient: propPatient }: { patientId: string; initialPatient?: Patient }) {
  const defaultPatient = propPatient || PATIENTS.find(p => p.id === patientId) || getStoredCustomPatients().find(p => p.id === patientId) || PATIENTS[0];
  const [patient, setPatient] = useState<Patient>(defaultPatient);
  const [copilotReport, setCopilotReport] = useState<CopilotReport | null>(null);
  const [copilotError, setCopilotError] = useState<string | null>(null);
  const [copilotErrorPatientId, setCopilotErrorPatientId] = useState<string | null>(null);
  const [isGeneratingReport, setIsGeneratingReport] = useState(false);

  useEffect(() => {
    let isMounted = true;
    const fetchLive = async () => {
      try {
        const livePatient = await getPatient(patientId);
        if (isMounted && livePatient) setPatient(livePatient);
      } catch (err) {
        console.warn('Using local cache for patient forecast:', err);
      }
    };
    fetchLive();
    return () => { isMounted = false; };
  }, [patientId]);

  const isHighRisk = patient.riskLevel === 'HIGH RISK';
  const handleGenerateReport = async () => {
    setIsGeneratingReport(true);
    setCopilotError(null);
    try {
      const report = await getPatientCopilotReport(patientId);
      setCopilotReport(report);
    } catch (error) {
      setCopilotError(error instanceof Error ? error.message : 'Report generation failed.');
      setCopilotErrorPatientId(patientId);
      setCopilotReport(null);
    } finally {
      setIsGeneratingReport(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Patient Vital Navigation Header & Tabs */}
      <PatientNavHeader patient={patient} />

      {/* Clinical Safety Banner per PRD Section 11 & 13 */}
      <div className="border border-[#12612F] bg-[#04130A] p-3 text-xs flex items-center justify-between">
        <div className="flex items-center space-x-2">
          <span className="w-2 h-2 bg-[#FFE14A] inline-block" />
          <span className="text-[#FFE14A] font-semibold uppercase tracking-wider">
            INVESTIGATIONAL CLINICAL DECISION SUPPORT
          </span>
          <span className="text-[#12612F]">|</span>
          <span className="text-[#2FBF63]">
            BreathTwin estimates flare-up risk probability with conformal uncertainty; does not issue diagnosis or autonomous prescriptions.
          </span>
        </div>
        <span className="text-[10px] font-mono text-[#B6FFCC] uppercase hidden md:inline">
          CALIBRATED WITH CONFORMAL PREDICTION
        </span>
      </div>

      {/* PRD FR-16: Learning Baseline Wide Uncertainty Band Banner for Newly Enrolled Twins */}
      {patient.learningBaseline?.active && (
        <div className="border border-[#FFE14A] bg-[#141103] p-4 space-y-2.5 text-xs">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="font-mono font-bold text-[#FFE14A] uppercase">
              [FR-16] {patient.learningBaseline.statusLabel} &bull; SIMULATED STREAM: {(patient.simulatedDeviceProfile || patient.learningBaseline.simulatedDeviceProfile || 'typical').toUpperCase()}
            </div>
            <span className="font-mono text-[#FFE14A] font-bold">
              WIDE INITIAL UNCERTAINTY BAND: &plusmn;{patient.learningBaseline.uncertaintyHalfWidthPct}%
            </span>
          </div>
          <p className="text-[#A7E8BD] text-[11px]">
            Wearable signals (SpO2, HR, RR) are generated by the simulator. Conformal uncertainty intervals start wide during initial baseline learning and narrow over the first 7 days of monitoring:
          </p>
          <div className="grid grid-cols-4 gap-2 pt-1 font-mono text-center">
            {[
              { label: 'Day 1 (Cold-Start)', width: '±22%', active: patient.learningBaseline.currentDay <= 2 },
              { label: 'Day 3 (Adapting)', width: '±16%', active: patient.learningBaseline.currentDay >= 3 && patient.learningBaseline.currentDay < 5 },
              { label: 'Day 5 (Converging)', width: '±11%', active: patient.learningBaseline.currentDay >= 5 && patient.learningBaseline.currentDay < 7 },
              { label: 'Day 7 (Calibrated)', width: '±7%', active: patient.learningBaseline.currentDay >= 7 },
            ].map((item) => (
              <div
                key={item.label}
                className={`p-2 border ${
                  item.active
                    ? 'border-[#FFE14A] bg-[#04130A] text-[#FFE14A] font-bold'
                    : 'border-[#12612F] bg-[#04130A]/60 text-[#2FBF63]'
                }`}
              >
                <div className="text-[10px]">{item.label}</div>
                <div className="text-xs font-bold mt-0.5">{item.width}</div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* 3-Stage Ensemble Stack Strip (Dilated TCN + XGBoost -> MLP Meta-Learner) */}
      {patient.basePredictions && (
        <div className="border border-[#12612F] bg-[#04130A] p-3.5 text-xs flex flex-wrap items-center justify-between gap-3 font-mono">
          <span className="text-[#2FBF63] font-bold uppercase">
            // 2-STAGE STACKED ENSEMBLE PIPELINE (48H HORIZON):
          </span>
          <div className="flex flex-wrap items-center gap-4">
            <span className="text-[#B6FFCC]">
              STAGE-1 DILATED TCN: <strong className="text-[#4CFF8A]">{patient.basePredictions.tcnRisk48h}%</strong>
            </span>
            <span className="text-[#12612F]">+</span>
            <span className="text-[#B6FFCC]">
              STAGE-1 XGBOOST: <strong className="text-[#4CFF8A]">{patient.basePredictions.gradientBoostingRisk48h}%</strong>
            </span>
            <span className="text-[#2FBF63]">&rarr;</span>
            <span className="px-2 py-0.5 border border-[#4CFF8A] bg-[#061C0E] text-[#4CFF8A] font-bold">
              STAGE-2 MLP META-LEARNER: {patient.basePredictions.metaRisk48h}%
            </span>
          </div>
        </div>
      )}

      {/* 24h & 48h Forecast Cards Strip */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {/* 24-Hour Horizon */}
        <div className="border border-[#12612F] bg-[#04130A] p-5 space-y-4">
          <div className="flex items-center justify-between border-b border-[#12612F]/40 pb-2">
            <div>
              <span className="text-[11px] font-medium tracking-[0.08em] uppercase text-[#2FBF63]">{`// 24-HOUR FORECAST HORIZON`}</span>
              <div className="text-xs text-[#B6FFCC] font-mono">TARGET: ADVERSE EVENT WITHIN 24H</div>
            </div>
            <StatusChip status={patient.risk24h >= 70 ? 'HIGH RISK' : patient.risk24h >= 50 ? 'ELEVATED' : 'NORMAL'} size="sm" />
          </div>

          <div className="flex items-baseline justify-between">
            <div>
              <div className="text-[10px] text-[#2FBF63] uppercase tracking-wider">EXACERBATION PROBABILITY</div>
              <div className={`text-4xl font-bold font-mono tabular-nums ${
                patient.risk24h >= 70 ? 'text-[#FF2A1A] glow-danger' : 
                patient.risk24h >= 50 ? 'text-[#FFA61F]' : 'text-[#4CFF8A]'
              }`}>
                {patient.risk24h}%
              </div>
            </div>
            <div className="text-right">
              <div className="text-[10px] text-[#2FBF63] uppercase tracking-wider">CONFORMAL 90% CI</div>
              <div className="text-sm font-mono text-[#B6FFCC]">
                [{patient.risk24hInterval[0]}% &mdash; {patient.risk24hInterval[1]}%]
              </div>
              <div className="text-[10px] text-[#2FBF63]">Calibrated uncertainty</div>
            </div>
          </div>

          <div className="border-t border-[#12612F]/30 pt-2 text-[11px] text-[#2FBF63]">
            {patient.risk24h >= 70 
              ? 'Acute inflammation acceleration underway. Early airway resistance elevated.'
              : 'Sub-acute physiological drift. Airway caliber currently maintained.'}
          </div>
        </div>

        {/* 48-Hour Horizon */}
        <div className={`border bg-[#04130A] p-5 space-y-4 ${
          isHighRisk ? 'border-[#FF2A1A]' : 'border-[#12612F]'
        }`}>
          <div className="flex items-center justify-between border-b border-[#12612F]/40 pb-2">
            <div>
              <span className="text-[11px] font-medium tracking-[0.08em] uppercase text-[#2FBF63]">{`// 48-HOUR PRIMARY CLINICAL HORIZON`}</span>
              <div className="text-xs text-[#B6FFCC] font-mono">TARGET: 48H ADVERSE EVENT PREDICTION</div>
            </div>
            <StatusChip status={patient.riskLevel} size="sm" />
          </div>

          <div className="flex items-baseline justify-between">
            <div>
              <div className="text-[10px] text-[#2FBF63] uppercase tracking-wider">48H PREDICTED RISK</div>
              <div className={`text-4xl font-bold font-mono tabular-nums ${
                isHighRisk ? 'text-[#FF2A1A] glow-danger' : 'text-[#B6FFCC]'
              }`}>
                {patient.risk48h}%
              </div>
            </div>
            <div className="text-right">
              <div className="text-[10px] text-[#2FBF63] uppercase tracking-wider">CONFORMAL 90% CI</div>
              <div className="text-sm font-mono text-[#B6FFCC]">
                [{patient.risk48hInterval[0]}% &mdash; {patient.risk48hInterval[1]}%]
              </div>
              <div className="text-[10px] text-[#2FBF63]">Alert Threshold: &gt; 70%</div>
            </div>
          </div>

          <div className="border-t border-[#12612F]/30 pt-2 flex items-center justify-between text-[11px]">
            <span className="text-[#FFE14A]">LEAD TIME AVAILABLE:</span>
            <span className="font-mono text-[#B6FFCC] font-bold">{patient.leadTimeHours} HOURS</span>
          </div>
        </div>
      </div>

      {/* Environmental Air-Quality Context & Forecast */}
      <div className="border border-[#12612F] bg-[#04130A] p-5 space-y-4">
        <div className="flex items-center justify-between border-b border-[#12612F]/40 pb-2">
          <div>
            <span className="text-[11px] font-medium tracking-[0.08em] uppercase text-[#2FBF63]">{`// AMBIENT POLLUTION CONTEXT • ${patient.city.toUpperCase()} (${patient.station})`}</span>
            <div className="text-xs text-[#B6FFCC] font-mono">STREAM: OPEN CPCB / OPENAQ INDIA REAL-TIME INGESTION</div>
          </div>
          <span className="text-xs font-mono text-[#FFE14A] border border-[#12612F] px-2 py-0.5 bg-[#020A05]">
            AQI: {patient.currentAirQuality.aqi} &bull; {patient.currentAirQuality.aqiCategory.toUpperCase()}
          </span>
        </div>

        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 text-xs">
          <div className="border border-[#12612F] bg-[#061C0E] p-3">
            <div className="text-[10px] text-[#2FBF63] uppercase">FINE PARTICLES (PM2.5)</div>
            <div className="text-xl font-bold font-mono text-[#FF2A1A] mt-1">{patient.currentAirQuality.pm25} µg/m³</div>
            <div className="text-[10px] text-[#2FBF63]">WHO Safe Limit: 15 µg/m³</div>
          </div>

          <div className="border border-[#12612F] bg-[#061C0E] p-3">
            <div className="text-[10px] text-[#2FBF63] uppercase">COARSE PARTICLES (PM10)</div>
            <div className="text-xl font-bold font-mono text-[#FFA61F] mt-1">{patient.currentAirQuality.pm10} µg/m³</div>
            <div className="text-[10px] text-[#2FBF63]">Bronchial upper airway irritant</div>
          </div>

          <div className="border border-[#12612F] bg-[#061C0E] p-3">
            <div className="text-[10px] text-[#2FBF63] uppercase">TEMPERATURE &amp; INVERSION</div>
            <div className="text-xl font-bold font-mono text-[#B6FFCC] mt-1">{patient.currentAirQuality.temp} &deg;C</div>
            <div className="text-[10px] text-[#2FBF63]">Cold nighttime trapping</div>
          </div>

          <div className="border border-[#12612F] bg-[#061C0E] p-3">
            <div className="text-[10px] text-[#2FBF63] uppercase">RELATIVE HUMIDITY</div>
            <div className="text-xl font-bold font-mono text-[#B6FFCC] mt-1">{patient.currentAirQuality.humidity}%</div>
            <div className="text-[10px] text-[#2FBF63]">Aerosol retention index</div>
          </div>
        </div>
      </div>

      {/* SHAP Explainability & Alert Reasons */}
      <div className="space-y-4">
        <div className="flex items-center justify-between border-b border-[#12612F] pb-2">
          <div>
            <h2 className="text-lg font-semibold text-[#B6FFCC] tracking-wide">{`// Explainable AI: Ranked Alert Drivers (SHAP Attribution)`}</h2>
            <div className="text-xs text-[#2FBF63]">
              Section 9 &amp; 11 Compliance: Never show a risk probability without auditable clinical reasons.
            </div>
          </div>
          <span className="text-xs font-mono text-[#4CFF8A]">
            METHOD: INTEGRATED GRADIENTS + LATENT DECOMPOSITION
          </span>
        </div>

        <div className="space-y-3">
          {patient.shapReasons.map((reason) => {
            const isUp = reason.direction === 'up';
            return (
              <div
                key={reason.rank}
                className="border border-[#12612F] bg-[#04130A] p-4 flex flex-col md:flex-row md:items-center justify-between gap-4 text-xs"
              >
                <div className="flex items-start space-x-3">
                  <div className="w-6 h-6 border border-[#12612F] bg-[#020A05] flex items-center justify-center font-mono font-bold text-[#B6FFCC] shrink-0">
                    {reason.rank}
                  </div>
                  <div>
                    <div className="flex items-center space-x-2">
                      <span className="font-semibold text-sm text-[#B6FFCC]">{reason.feature}</span>
                      <span className="text-[10px] font-mono px-1.5 py-0.2 border border-[#12612F] text-[#4CFF8A] uppercase">
                        {reason.targetStream}
                      </span>
                    </div>
                    <p className="text-xs text-[#2FBF63] mt-1 leading-relaxed max-w-3xl">
                      {reason.description}
                    </p>
                  </div>
                </div>

                <div className="flex items-center space-x-4 shrink-0 border-t md:border-t-0 border-[#12612F]/40 pt-2 md:pt-0">
                  <div className="text-right">
                    <div className="text-[10px] uppercase text-[#2FBF63]">RISK IMPACT</div>
                    <div className={`font-mono text-base font-bold ${
                      isUp ? 'text-[#FF2A1A]' : 'text-[#4CFF8A]'
                    }`}>
                      {isUp ? `+${reason.impactPercent}%` : `-${reason.impactPercent}%`}
                    </div>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {/* Patient-specific report generated from backend inference */}
      <section className="border border-[#12612F] bg-[#04130A] p-5 space-y-4" aria-live="polite">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-[#12612F]/40 pb-3">
          <div>
            <h2 className="text-lg font-semibold text-[#B6FFCC] tracking-wide">
              {'// Patient Copilot Report'}
            </h2>
            <p className="text-xs text-[#2FBF63] mt-1">
              Draft generated from this patient&apos;s backend model forecast and recent telemetry.
            </p>
          </div>
          <button
            type="button"
            onClick={handleGenerateReport}
            disabled={isGeneratingReport}
            className="h-10 px-4 text-xs uppercase tracking-wider font-semibold border border-[#4CFF8A] text-[#4CFF8A] hover:bg-[#4CFF8A] hover:text-[#020A05] disabled:opacity-50 disabled:cursor-wait transition-colors"
          >
            {isGeneratingReport ? 'GENERATING REPORT...' : 'GENERATE REPORT'}
          </button>
        </div>

        {copilotError && copilotErrorPatientId === patientId && (
          <p role="alert" className="border border-[#FF2A1A]/60 bg-[#1B0806] p-3 text-sm text-[#FF9A8F]">
            {copilotError}
          </p>
        )}

        {copilotReport && copilotReport.patient_id === patientId && (
          <div className="space-y-4 text-sm text-[#B6FFCC]">
            <div className="flex flex-wrap items-center gap-3">
              <span className="border border-[#12612F] px-2 py-1 text-xs uppercase">
                {copilotReport.clinical_status}
              </span>
              <span className="text-xs text-[#2FBF63] uppercase">
                Model risk: {copilotReport.risk_level}
              </span>
              <span className="text-xs text-[#2FBF63]">Patient: {copilotReport.patient_id}</span>
            </div>
            <p>{copilotReport.summary_reason}</p>

            <div className="grid gap-4 md:grid-cols-2">
              <div>
                <h3 className="text-xs font-semibold uppercase text-[#4CFF8A]">Precautions</h3>
                {copilotReport.precautions.length > 0 ? (
                  <ul className="list-disc pl-5 mt-2 space-y-1">
                    {copilotReport.precautions.map((item, index) => <li key={index}>{item}</li>)}
                  </ul>
                ) : <p className="mt-2 text-xs text-[#2FBF63]">No precautions were returned.</p>}
              </div>
              <div>
                <h3 className="text-xs font-semibold uppercase text-[#4CFF8A]">Recorded triggers</h3>
                {copilotReport.triggers_to_avoid.length > 0 ? (
                  <ul className="list-disc pl-5 mt-2 space-y-1">
                    {copilotReport.triggers_to_avoid.map((item, index) => <li key={index}>{item}</li>)}
                  </ul>
                ) : <p className="mt-2 text-xs text-[#2FBF63]">No patient-specific triggers are recorded.</p>}
              </div>
            </div>

            <div className="border-t border-[#12612F]/40 pt-3 space-y-2 text-xs">
              <p><span className="font-semibold text-[#4CFF8A]">Medication:</span> {copilotReport.medication_guidance.action} {copilotReport.medication_guidance.note}</p>
              {copilotReport.breathing_exercise && (
                <div>
                  <span className="font-semibold text-[#4CFF8A]">Breathing exercise:</span>{' '}
                  {copilotReport.breathing_exercise.name} — {copilotReport.breathing_exercise.purpose}
                  <ul className="list-disc pl-5 mt-1">
                    {copilotReport.breathing_exercise.how_to_do_it.map((step, index) => <li key={index}>{step}</li>)}
                  </ul>
                  <p>{copilotReport.breathing_exercise.duration}</p>
                </div>
              )}
              <p><span className="font-semibold text-[#4CFF8A]">Emergency warning:</span> {copilotReport.emergency_warning}</p>
            </div>
            <p className="border-l-2 border-[#FFE14A] pl-3 text-xs text-[#FFE14A]">
              AI-generated investigational draft for clinician review; not a diagnosis or treatment instruction.
            </p>
          </div>
        )}
      </section>

      {/* Action to What-If Sandbox */}
      <div className="border border-[#12612F] bg-[#061C0E] p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="text-xs font-semibold uppercase text-[#B6FFCC]">
            &gt; READY TO EVALUATE CLINICAL COUNTERFACTUALS?
          </div>
          <p className="text-xs text-[#2FBF63] mt-0.5">
            Test whether staying indoors, wearing an N95 respirator, or boosting steroid controller adherence brings 48h risk below alert threshold.
          </p>
        </div>

        <Link
          href={`/patients/${patient.id}/what-if`}
          className="h-11 px-6 text-xs uppercase tracking-wider font-semibold border border-[#4CFF8A] text-[#4CFF8A] hover:bg-[#4CFF8A] hover:text-[#020A05] transition-colors flex items-center justify-center shrink-0"
        >
          OPEN WHAT-IF SANDBOX &gt;
        </Link>
      </div>
    </div>
  );
}
